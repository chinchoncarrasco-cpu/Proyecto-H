const temporizadoresFeedbackCopiaDetalle = new WeakMap();

async function copiarTextoDetalleRevision(texto) {

    if (navigator.clipboard?.writeText) {
        try {
            await navigator.clipboard.writeText(texto);
            return;
        } catch (_) {
            // Algunos navegadores bloquean Clipboard API fuera de contexto
            // seguro; mantenemos un fallback local para esos casos.
        }
    }

    const auxiliar = document.createElement("textarea");
    auxiliar.value = texto;
    auxiliar.setAttribute("readonly", "");
    auxiliar.style.position = "fixed";
    auxiliar.style.opacity = "0";
    auxiliar.style.pointerEvents = "none";
    document.body.appendChild(auxiliar);

    let copiado = false;

    try {
        auxiliar.select();
        auxiliar.setSelectionRange(0, auxiliar.value.length);
        copiado = document.execCommand?.("copy") === true;
    } finally {
        auxiliar.remove();
    }

    if (!copiado) {
        throw new Error("El navegador no permitió copiar el detalle.");
    }
}

function mostrarFeedbackCopiaDetalle(
    boton,
    estado,
    mensaje,
    etiquetaOriginal,
    estadoAccesible
) {

    const temporizadorAnterior =
        temporizadoresFeedbackCopiaDetalle.get(boton);

    if (temporizadorAnterior) {
        clearTimeout(temporizadorAnterior);
    }

    boton.dataset.estadoCopia = estado;
    boton.dataset.feedback = mensaje;
    boton.setAttribute("aria-label", estadoAccesible);

    const estadoVisible = boton.parentElement?.querySelector(
        ".checklist-section-detail-copy-status"
    );

    if (estadoVisible) {
        estadoVisible.textContent = mensaje;
    }

    const temporizador = setTimeout(() => {
        delete boton.dataset.estadoCopia;
        delete boton.dataset.feedback;
        boton.setAttribute("aria-label", etiquetaOriginal);

        if (estadoVisible) {
            estadoVisible.textContent = "";
        }

        temporizadoresFeedbackCopiaDetalle.delete(boton);
    }, 1300);

    temporizadoresFeedbackCopiaDetalle.set(boton, temporizador);
}

function obtenerDetalleRevisionPorArea(nombreArea) {

    const nombreNormalizado = String(nombreArea || "")
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toUpperCase();

    return detallesRevisionPorSector.find(detalle =>
        nombreNormalizado.includes(detalle.coincidencia)
    ) || null;
}

function crearDetalleRevisionSector(
    contenedor,
    nombreArea,
    numeroCabana
) {

    const detalle = obtenerDetalleRevisionPorArea(nombreArea);

    if (!detalle) {
        return;
    }

    const etiqueta = document.createElement("label");
    etiqueta.className = "checklist-section-detail";

    const titulo = document.createElement("span");
    titulo.className = "checklist-section-detail-label";
    titulo.textContent = "Detalle";

    const textarea = document.createElement("textarea");
    textarea.className = "checklist-section-detail-input";
    textarea.rows = 2;
    textarea.dataset.revisionDetalleSeccion = detalle.campo;
    textarea.setAttribute(
        "aria-label",
        `Detalle de ${detalle.nombre}`
    );
    textarea.placeholder = `Observación de ${detalle.nombre}`;

    const datosDia = obtenerDatosDia(fechaSeleccionada);
    const datosCabana = datosDia.cabanas[numeroCabana] || {};
    const detallesGuardados =
        datosCabana.detallesRevisionSeccion || {};

    textarea.value = detallesGuardados[detalle.campo] || "";

    const etiquetaCopiar = `Copiar detalle de ${detalle.nombre}`;
    const botonCopiar = document.createElement("button");
    botonCopiar.type = "button";
    botonCopiar.className = "checklist-section-detail-copy";
    botonCopiar.dataset.copiarDetalleSeccion = detalle.campo;
    botonCopiar.setAttribute("aria-label", etiquetaCopiar);
    botonCopiar.title = etiquetaCopiar;
    botonCopiar.innerHTML = `
        <svg class="copy-icon copy-icon-default" viewBox="0 0 20 20" aria-hidden="true">
            <rect x="6.5" y="6.5" width="9" height="10" rx="1.5"></rect>
            <path d="M4.5 13.5h-1a1.5 1.5 0 0 1-1.5-1.5V3.5A1.5 1.5 0 0 1 3.5 2h8A1.5 1.5 0 0 1 13 3.5v1"></path>
        </svg>
        <svg class="copy-icon copy-icon-success" viewBox="0 0 20 20" aria-hidden="true">
            <path d="m4 10.5 3.5 3.5L16 5.5"></path>
        </svg>
    `;

    const estadoCopia = document.createElement("span");
    estadoCopia.className = "checklist-section-detail-copy-status";
    estadoCopia.setAttribute("aria-live", "polite");
    estadoCopia.setAttribute("aria-atomic", "true");

    botonCopiar.addEventListener("click", async evento => {
        evento.preventDefault();
        evento.stopPropagation();

        const texto = textarea.value;

        if (!texto.trim()) {
            mostrarFeedbackCopiaDetalle(
                botonCopiar,
                "vacio",
                "Sin texto",
                etiquetaCopiar,
                `No hay texto en el detalle de ${detalle.nombre}`
            );
            return;
        }

        try {
            await copiarTextoDetalleRevision(texto);
            mostrarFeedbackCopiaDetalle(
                botonCopiar,
                "copiado",
                "Copiado",
                etiquetaCopiar,
                `Detalle de ${detalle.nombre} copiado`
            );
        } catch (error) {
            console.error(
                "HAIKU · No fue posible copiar el detalle de revisión:",
                error
            );
            mostrarFeedbackCopiaDetalle(
                botonCopiar,
                "error",
                "No se pudo copiar",
                etiquetaCopiar,
                `No fue posible copiar el detalle de ${detalle.nombre}`
            );
        }
    });

    etiqueta.appendChild(titulo);
    etiqueta.appendChild(botonCopiar);
    etiqueta.appendChild(estadoCopia);
    etiqueta.appendChild(textarea);
    contenedor.appendChild(etiqueta);
}

function mostrarChecklistCabana(numeroCabana) {

    const contenedor =
        document.getElementById("revision-checklist");

    if (!contenedor) {
        return;
    }

    contenedor.innerHTML = "";

    const checklist =
        checklistsCabanas[numeroCabana];

    if (!checklist) {

        contenedor.innerHTML =
            "<p>Checklist aún no configurado.</p>";

        return;
    }


    checklist.forEach((bloque, indiceArea) => {

        const area = document.createElement("div");

        area.className = "checklist-area";


        const titulo = document.createElement("h4");

        titulo.textContent = bloque.area;

        area.appendChild(titulo);


        // Áreas que contienen subáreas

        if (bloque.subareas) {

            bloque.subareas.forEach(
                (subarea, indiceSubarea) => {

                    const subtitulo =
                        document.createElement("h5");

                    subtitulo.textContent =
                        subarea.nombre;

                    area.appendChild(subtitulo);


                    crearItemsChecklist(
                        area,
                        subarea.items,
                        numeroCabana,
                        `${indiceArea}-${indiceSubarea}`
                    );

                }
            );

        }


        // Áreas normales

        if (bloque.items) {

            crearItemsChecklist(
                area,
                bloque.items,
                numeroCabana,
                `${indiceArea}`
            );

        }

        crearDetalleRevisionSector(
            area,
            bloque.area,
            numeroCabana
        );


        contenedor.appendChild(area);

    });

}

